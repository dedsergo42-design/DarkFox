#pragma once

#include <cstdint>
#include <string>
#include <vector>

#include <core/systems/systems.hpp>

namespace features::misc
{
	// Хранилище прострелов на диск, по файлу на карту.
	//
	// Зачем файл, а не память. Скан карты -- это тысячи трасс: сетка вокруг
	// игрока плюс веер по прицелу. Внутри одной сессии он окупается, но при
	// каждом рестарте игры всё считается заново, и первые секунды раунда
	// ragebot ничего не знает о прострелах. Файл превращает разовую работу
	// в постоянную: посчитал один раз на карте -- пользуешься всегда.
	//
	// Формат. Данные обфусцированы, потому что это не служебный кэш, а
	// разметка карты: список мест, где стреляет сквозь стену. В открытом
	// виде это читается как готовый wallbang-конфиг -- достаточно открыть
	// файл и получить все точки. Задача не в защите от реверса (клиент всё
	// равно держит их в памяти в открытом виде), а в том, чтобы файл не
	// был полезен тому, кто просто нашёл его на диске.
	//
	// Как устроена обфускация. Три слоя, каждый дешёвый, но вместе они
	// ломают любой наивный просмотр:
	//
	//   1. XTEA-подобный блочный шифр на 64-битных блоках. Ключ -- константа
	//      модуля, смешанная с хэшем имени карты: файл одной карты нельзя
	//      подсунуть другой (см. mix_key).
	//   2. Побайтовый XOR с гаммой, порождённой xorshift64 от того же ключа.
	//      Даёт лавину: изменение одного байта портит весь поток.
	//   3. Заголовок-обманка. Первые байты -- не магия, а правдоподобный
	//      мусор, чтобы file(1) и hex-редактор не подсказывали формат.
	//
	// Целостность. В конце -- контрольная сумма (FNV-1a) по明文 данным.
	// Битый или чужой файл не роняет фичу: загрузка возвращает пустой
	// список, и скан просто отрабатывает заново.
	//
	// Количество прострелов тоже шифруется -- иначе размер файла выдавал бы
	// число меток.
	class map_store
	{
	public:
		// Одна запись прострела на диске. Совпадает по смыслу с
		// map_scan::marker, но живёт отдельно: хранилище не должно зависеть
		// от класса сканера.
		struct entry
		{
			math::vector3 position{};
			math::vector3 normal{};
			math::vector3 end{};
			float damage{};
			float distance{};
		};

		// Куда пишем. Каталог рядом с модулем: <папка DLL>/df_maps/.
		// Если модуль определить не удалось -- текущий рабочий каталог.
		[[nodiscard]] static std::string directory( );

		// Путь к файлу конкретной карты. Имя карты чистится от разделителей
		// и приводится к нижнему регистру, чтобы de_dust2 и DE_DUST2
		// не разводили два файла.
		[[nodiscard]] static std::string path_for( const std::string& map_name );

		// Канонизация имени карты: нижний регистр, только [a-z0-9_-],
		// без расширения .bsp и без пути. Одна на весь модуль -- ключ
		// шифрования обязан считаться от ТОГО ЖЕ имени, что и имя файла:
		// иначе "de_dust2.bsp" сохранится как de_dust2.dfm, но ключом от
		// "de_dust2.bsp", и при загрузке по "de_dust2" файл не прочтётся.
		[[nodiscard]] static std::string canonical_name( const std::string& map_name );

		// Сохранить набор прострелов. Возвращает false, если файл открыть
		// не удалось. Каталог создаётся при необходимости.
		[[nodiscard]] static bool save( const std::string& map_name, const std::vector<entry>& entries );

		// Загрузить набор прострелов. Пустой вектор -- и "файла нет", и
		// "файл битый"; вызывающего это устраивает одинаково.
		[[nodiscard]] static std::vector<entry> load( const std::string& map_name );

		// Стереть файл карты (на случай порчи данных).
		[[nodiscard]] static bool erase( const std::string& map_name );

	private:
		// Ключ на карту: константа модуля, смешанная с FNV-1a от имени.
		// 64 бита, чтобы XTEA работал на полном блоке.
		[[nodiscard]] static std::uint64_t mix_key( const std::string& map_name );

		[[nodiscard]] static std::uint64_t checksum( const std::uint8_t* data, std::size_t size );

		// Единый проход обфускации. Порядок слоёв задаётся флагом:
		// при шифровании сначала блочный слой, потом XOR; при расшифровке
		// -- строго наоборот. XTEA не симметричен сам себе, поэтому одного
		// вызова "туда и обратно" недостаточно.
		static void crypt( std::uint8_t* data, std::size_t size, std::uint64_t key, bool encrypt );

		static void xtea_encrypt( std::uint32_t& v0, std::uint32_t& v1, const std::uint32_t key[ 4 ] );
		static void xtea_decrypt( std::uint32_t& v0, std::uint32_t& v1, const std::uint32_t key[ 4 ] );

		// Версия формата. Меняется, когда меняется раскладка записи;
		// чужую версию не пытаемся разобрать.
		static constexpr auto k_version{ 1u };

		// Заголовок-обманка: 16 байт мусора перед полезной нагрузкой.
		// Не магия -- именно чтобы не читалось как формат.
		static constexpr auto k_decoy_size{ 16u };

		// Размер одной записи на диске: 3 вектора по 3 float + 2 float.
		// Пишем покомпонентно в little-endian, без реструктуризации
		// структур -- раскладка не должна зависеть от компилятора.
		static constexpr auto k_entry_floats{ 11u };
	};
}
